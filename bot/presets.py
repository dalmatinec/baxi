def next_value(values: list, current) -> object:
    """Следующее значение по кругу."""
    for v in values:
        if v > current + 1e-9:
            return v
    return values[0]


def pct(v: float) -> str:
    return f"{round(v * 100)}%"


def every(chance: float) -> str:
    """Шанс в доли в человеческом виде: «примерно раз в 25 сообщений»."""
    if chance <= 0:
        return "сам не влезаю, только отвечаю, когда зовут"
    return f"примерно раз в {round(1 / chance)} сообщений"


def quiet_text(start: int, end: int) -> str:
    return "выкл" if start < 0 else f"{start:02d}:00-{end:02d}:00"


def in_quiet(hour: int, start: int, end: int) -> bool:
    """Попадает ли час в тихие часы (с переходом через полночь)."""
    if start < 0 or start == end:
        return False
    if start < end:
        return start <= hour < end
    return hour >= start or hour < end
