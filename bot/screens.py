def rows(buttons: list[dict]) -> list[list[dict]]:
    """Кнопки по рядам в порядке номеров рядов."""
    out: dict[int, list[dict]] = {}
    for b in buttons:
        out.setdefault(int(b.get("row", 0)), []).append(b)
    return [out[k] for k in sorted(out)]


def fill(text: str, values: dict) -> str:
    """Подставляет {name}, {chats} и т.п. Неизвестные {скобки} оставляет как есть."""
    for key, value in values.items():
        text = text.replace("{" + key + "}", str(value))
    return text
