_TOKEN = re.compile(r"[a-zа-яёәғқңөұүһі]+", re.I)
SLANG = {k.replace("ё", "е"): v for k, v in SLANG.items()}
_PHRASES = [k for k in SLANG if " " in k]   # «на мели», «зуб даю»: ищем целиком


def found(texts: list[str], limit: int = 12) -> list[str]:
    """Строки «слово = значение» для сленга, который встретился в этих сообщениях."""
    seen: dict[str, str] = {}
    for text in texts:
        low = (text or "").lower().replace("ё", "е")
        toks = _TOKEN.findall(low)
        joined = " " + " ".join(toks) + " "
        for ph in _PHRASES:
            if f" {ph} " in joined and ph not in seen:
                seen[ph] = SLANG[ph]
        for tok in toks:
            if tok in SLANG and tok not in seen and not any(tok in ph.split() for ph in seen if " " in ph):
                seen[tok] = SLANG[tok]
    return [f"{k} = {v}" for k, v in list(seen.items())[-limit:]]


def hint(texts: list[str]) -> str:
    lines = found(texts)
    if not lines:
        return ""
    return ("Сленг в этом разговоре (пойми его, но сам за людьми не повторяй): " + "; ".join(lines) + ". "
            "Грубое словечко или эмоция вроде «збл» это не оскорбление: не отвечай «сам такой», отвечай на смысл.")
