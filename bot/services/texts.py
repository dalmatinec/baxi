def groups() -> list[str]:
    seen = []
    for group, *_ in TEXTS.values():
        if group not in seen:
            seen.append(group)
    return seen


def fill(template: str, values: dict[str, object]) -> str:
    for key, value in values.items():
        template = template.replace("{" + key + "}", str(value))
    return template


def sample(key: str, template: str) -> str:
    """Как текст будет выглядеть с примерами вместо подстановок."""
    return fill(template, {k: v[1] for k, v in TEXTS[key][3].items()})


async def render(key: str, **values) -> str:
    """Свой текст владельца или стандартный, с подставленными значениями."""
    from bot import db
    template = await db.kv_get(key) or TEXTS[key][2]
    return fill(template, values)
