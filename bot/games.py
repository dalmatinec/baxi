def ship_percent(a: int, b: int, day: str) -> int:
    """Совместимость двух людей. В течение дня одна и та же, завтра другая."""
    lo, hi = sorted((a, b))
    digest = hashlib.sha256(f"{lo}:{hi}:{day}".encode()).digest()
    return digest[0] * 101 // 256


def ship_comment(p: int) -> str:
    if p >= 90:
        return "это судьба, женитесь 💍"
    if p >= 70:
        return "искра есть, дальше сами 🔥"
    if p >= 50:
        return "ну можно попробовать 😏"
    if p >= 25:
        return "лучше просто дружить 🤝"
    return "даже не начинайте 💔"


def ship_bar(p: int) -> str:
    full = round(p / 10)
    return "❤️" * full + "🤍" * (10 - full)


def pick_couple(user_ids: list[int], rnd: random.Random | None = None) -> tuple[int, int] | None:
    pool = list(dict.fromkeys(user_ids))
    if len(pool) < 2:
        return None
    a, b = (rnd or random).sample(pool, 2)
    return a, b


_TRIGGERS = [
    ("quiz_top", re.compile(r"^\s*топ\s+(викторины|знатоков)\s*$", re.I)),
    ("rep_top", re.compile(r"^\s*(топ репы|топ репутации|топ чата|/top)(@\w+)?\s*$", re.I)),
    ("rep_me", re.compile(r"^\s*(репа|моя репа|репутация|моя репутация)\s*[?!.]*\s*$", re.I)),
    ("bdays", re.compile(r"^\s*(дни рождения|у кого др|/bdays)(@\w+)?\s*[?]*\s*$", re.I)),
    ("quiz", re.compile(r"^\s*(/?викторина|/quiz)(@\w+)?\s*[!?.]*\s*$", re.I)),
    ("couple", re.compile(r"^\s*(пара дня|парочка дня)\s*[!?.]*\s*$", re.I)),
    ("ship", re.compile(r"^\s*шип(пер|перим)?\s*[!?.]*\s*$", re.I)),
    ("who", re.compile(r"^\s*кто\s+(.{2,80})$", re.I)),
    ("predict", re.compile(r"^\s*(предсказание|предскажи)\s*[!?.]*\s*$", re.I)),
    ("help", re.compile(r"^\s*(/?игры|/games)(@\w+)?\s*$", re.I)),
]


def match(text: str) -> tuple[str, str] | None:
    """Какая игра вызвана сообщением. Возвращает (игра, хвост текста)."""
    for name, rx in _TRIGGERS:
        m = rx.match(text or "")
        if m:
            tail = m.group(1) if name == "who" else ""
            return name, tail.strip().rstrip("?!.")
    return None
