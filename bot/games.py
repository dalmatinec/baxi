def ship_bar(p: int) -> str:
    full = round(p / 10)
    return "❤️" * full + "🤍" * (10 - full)


def pick_couple(user_ids: list[int], rnd: random.Random | None = None) -> tuple[int, int] | None:
    pool = list(dict.fromkeys(user_ids))
    if len(pool) < 2:
        return None
    a, b = (rnd or random).sample(pool, 2)
    return a, b


