_PREFIX = re.compile(r"^\s*[\w\s]{1,30}\s*(\(это ты\))?\s*:\s+")
_BRACKET = re.compile(r"^\s*\[[^\]\n]{1,80}\]\s*:\s*")   # модель скопировала служебную пометку [Имя]: из переписки


HELLO_WORDS = r"(?:салам(?:алейкум)?|салем|сәлем|привет(?:ик)?|прив|здарова|здаров|хай|хей|йоу|ку|дарова|хелло)"
_HELLO_START = re.compile(rf"^\s*{HELLO_WORDS}(?!\w)(?:[\s,!.]+(?:бро|братан|братишка|брат|дружище|чел)(?!\w))?[\s,!.)]*", re.I)
_HELLO_IN = re.compile(rf"(?<!\w){HELLO_WORDS}(?!\w)", re.I)


def drop_hello(reply: str, incoming: str) -> str:
    """Убирает «салам бро» в начале ответа, если человек сам не здоровался. Модель любит копировать
    свои прошлые приветствия из переписки, и потом каждый ответ начинается одинаково."""
    if not reply or _HELLO_IN.search(incoming or ""):
        return reply
    rest = _HELLO_START.sub("", reply, count=1).strip()
    return rest or reply


