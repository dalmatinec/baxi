NO_AI_TELLS = ("Никогда не ставь длинное тире и кавычки-ёлочки: вместо тире дефис или запятая, "
               "кавычек лучше не ставить вообще.")
SAFE_HUMOR = ("Без шуток про национальность, религию, болезни и смерть конкретных людей из чата, "
              "без угроз и без пошлости про детей.")


def transcript(rows, limit: int = 300, cut: int = 160) -> str:
    """Переписка для выжимки: последние limit сообщений людей, каждое обрезано."""
    lines = []
    for r in [r for r in rows if not r["is_bot"]][-limit:]:
        text = " ".join(r["text"].split())[:cut]
        to = f" → {r['reply_name']}" if r["reply_name"] else ""
        lines.append(f"{r['name']}{to}: {text}")
    return "\n".join(lines)


