def roast_task(target: str, notes: str, messages: list[str], stats: str) -> str:
    said = "\n".join(f"- {m}" for m in messages[-25:]) or "(почти ничего не писал)"
    return (f"Тебя попросили прожарить участника {target}.\n"
            f"Что о нём известно: {notes or 'почти ничего'}\n{stats}\n"
            f"Его последние сообщения:\n{said}\n\n"
            "Прожарь его по-дружески: 2-4 коротких колких предложения, смешно, цепляйся за то, что он писал "
            "и что о нём известно. Можно жёстко, но без оскорблений по национальности, религии, внешности "
            "и здоровью, без угроз. Обращайся к нему по имени. " + NO_AI_TELLS)


